export function formatTime(value: string, locale: Locale) {
  return new Intl.DateTimeFormat(locale, {timeZone: 'Asia/Taipei', month: 'short', day: '2-digit', hour: '2-digit', minute: '2-digit', hourCycle: 'h23'}).format(new Date(value)) + ' UTC+08:00';
}
